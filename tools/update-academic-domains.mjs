#!/usr/bin/env node
// Regenerates api/src/auth/academic-domains.generated.ts from a downloaded copy of
// https://github.com/Hipo/university-domains-list (MIT License, Copyright (c) 2014-2025 Hipo).
// Usage: node tools/update-academic-domains.mjs path/to/world_universities_and_domains.json
import { readFileSync, writeFileSync } from "node:fs";

const source = process.argv[2];
if (!source) { console.error("Pass the path to world_universities_and_domains.json"); process.exit(1); }
const hostname = /^(?=.{3,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/;
// Shared hosting or second-level suffixes must never count as a school.
const blocked = /(^|\.)(blogspot\.com|wordpress\.com|wixsite\.com|weebly\.com|github\.io|google\.com|gmail\.com|outlook\.com|hotmail\.com|yahoo\.com|qq\.com|163\.com|126\.com)$/;
const entries = JSON.parse(readFileSync(source, "utf8"));
const domains = [...new Set(entries.flatMap(entry => entry.domains ?? []).map(domain => String(domain).trim().toLowerCase().replace(/\.$/, "")))]
  .filter(domain => hostname.test(domain) && !blocked.test(domain) && domain.includes("."))
  .sort();
const license = readFileSync(new URL("../api/src/auth/academic-domains.LICENSE.txt", import.meta.url), "utf8").trim().split("\n").map(line => `// ${line}`.trimEnd()).join("\n");
const body = `// Generated by tools/update-academic-domains.mjs. Do not edit by hand.
// Source: https://github.com/Hipo/university-domains-list (${domains.length} domains)
//
${license}
export const ACADEMIC_DOMAINS = ${JSON.stringify(domains.join(" "))};
`;
writeFileSync(new URL("../api/src/auth/academic-domains.generated.ts", import.meta.url), body);
console.log(`${domains.length} domains written`);
