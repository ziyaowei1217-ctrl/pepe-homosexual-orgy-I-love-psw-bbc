"""Split the psw rounded fonts into small web font files.

Browsers download a file only when the page shows a character in its `unicode-range`,
so a page loads the shared "core" file plus, at most, a few small extra files.

- Bold (titles, buttons): one core file with every character the UI copy uses
  (all Chinese text in app/, components/ and lib/, plus ASCII and punctuation),
  then the rest of the font in files of SLICE characters each.
- Heavy (big slogans only): just the characters of the slogans, which use `font-slogan`.

Output: public/fonts/psw/*.woff2 and app/psw-fonts.css. Run from the repository root
after changing UI copy or slogans (needs `pip install fonttools brotli`):

    python3 design/psw/fonts/subset.py
"""
import pathlib
import re

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[3]
SOURCE = ROOT / "design/psw/fonts"
OUT = ROOT / "public/fonts/psw"
CSS = ROOT / "app/psw-fonts.css"
SLICE = 200
CJK = re.compile(r"[　-〿一-鿿＀-￯‐-⁯]")
# Text set in font-slogan. Keep in sync with the components that use the class.
SLOGANS = "下一站，住得自在。"


def source_chars():
    chars = set(chr(c) for c in range(0x20, 0x7F))
    for folder in ("app", "components", "lib"):
        for path in (ROOT / folder).rglob("*"):
            if path.suffix in {".ts", ".tsx"}:
                chars |= set(CJK.findall(path.read_text(encoding="utf-8")))
    return chars


def ranges(codepoints):
    cps = sorted(codepoints)
    out, start, prev = [], cps[0], cps[0]
    for cp in cps[1:]:
        if cp == prev + 1:
            prev = cp
            continue
        out.append((start, prev))
        start = prev = cp
    out.append((start, prev))
    return ", ".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in out)


def write_subset(font_path, codepoints, out_path):
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.notdef_outline = True
    font = subset.load_font(str(font_path), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    subset.save_font(font, str(out_path), options)
    return out_path.stat().st_size


def face(family, file, codepoints):
    return (
        "@font-face {\n"
        f'  font-family: "{family}";\n'
        f'  src: url("/fonts/psw/{file}") format("woff2");\n'
        "  font-weight: 600 900;\n"
        "  font-style: normal;\n"
        "  font-display: swap;\n"
        f"  unicode-range: {ranges(codepoints)};\n"
        "}\n"
    )


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.woff2"):
        old.unlink()
    bold = SOURCE / "psw-rounded-bold.woff2"
    heavy = SOURCE / "psw-rounded-heavy.woff2"
    available = set(TTFont(str(bold)).getBestCmap())

    core = sorted(cp for cp in map(ord, source_chars()) if cp in available)
    rest = sorted(available - set(core) - {0x20})
    css = ["/* Generated by design/psw/fonts/subset.py. Do not edit by hand. */\n"]
    sizes = []

    size = write_subset(bold, core, OUT / "rounded-bold-core.woff2")
    sizes.append(("rounded-bold-core.woff2", len(core), size))
    css.append(face("psw Rounded", "rounded-bold-core.woff2", core))
    for index in range(0, len(rest), SLICE):
        part = rest[index:index + SLICE]
        name = f"rounded-bold-{index // SLICE + 1:02d}.woff2"
        size = write_subset(bold, part, OUT / name)
        sizes.append((name, len(part), size))
        css.append(face("psw Rounded", name, part))

    slogan = sorted(set(map(ord, SLOGANS)))
    size = write_subset(heavy, slogan, OUT / "slogan-heavy.woff2")
    sizes.append(("slogan-heavy.woff2", len(slogan), size))
    css.append(face("psw Slogan", "slogan-heavy.woff2", slogan))

    CSS.write_text("\n".join(css), encoding="utf-8")
    for name, count, size in sizes:
        print(f"{name:28} {count:5} chars {size / 1024:7.1f} KB")


if __name__ == "__main__":
    main()
